"""Build report/report.md and report/report.pdf from report_template.md.

{{key}}        -> value from paper/data/facts.json (same numbers as the paper)
{{table:name}} -> report/tables/<name>.md (generated by paper/tools/build_facts.py)
{{jsonlist}}   -> list of every result JSON in results/
PDF: markdown -> HTML (python-markdown) -> PDF (xhtml2pdf). Run with PYTHONPATH pointing at those packages.
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REP = REPO / "report"


def main():
    raw = json.loads((REPO / "paper/data/facts.json").read_text())

    def mname(k):  # same naming as paper/macros.tex
        for a, b in [("34", "ThirtyFour"), ("2", "Two"), ("8", "Eight")]:
            k = k.replace(a, b)
        return re.sub(r"[^A-Za-z]", "", k)

    facts = {mname(k): v for k, v in raw.items()}
    tpl = (REP / "tools/report_template.md").read_text()

    def val(k):
        if k not in facts:
            sys.exit(f"unknown fact {k}")
        return facts[k]["value"].replace("\\%", "%").replace("\\_", "_")

    def table(name):
        t = (REP / "tables" / f"{name}.md").read_text()
        if name in ("missing",):
            return t
        cap, _, body = t.partition("\n\n")
        return body.strip() + "\n\n*" + cap.strip("*") + "*"

    files = sorted(p.relative_to(REPO).as_posix() for p in (REPO / "results").rglob("*.json"))
    out = re.sub(r"\{\{table:(\w+)\}\}", lambda m: table(m.group(1)), tpl)
    out = out.replace("{{jsonlist}}", "\n".join(f"- `{f}`" for f in files))
    out = re.sub(r"\{\{(\w+)\}\}", lambda m: val(m.group(1)), out)
    left = re.findall(r"\{\{[^}]*\}\}", out)
    assert not left, left
    (REP / "report.md").write_text(out)
    print("report.md written:", len(out.splitlines()), "lines,", len(files), "result files listed")

    try:
        import markdown
        from xhtml2pdf import pisa
    except ImportError:
        print("markdown/xhtml2pdf not available: PDF skipped")
        return
    body = markdown.markdown(out, extensions=["tables", "fenced_code", "md_in_html"])
    body = body.replace('src="figures/', f'src="{(REP / "figures").as_posix()}/')
    import matplotlib
    ttf = Path(matplotlib.get_data_path()) / "fonts/ttf"
    css = f"""
    @font-face {{ font-family: DejaVu; src: url("{ttf}/DejaVuSans.ttf"); }}
    @font-face {{ font-family: DejaVu; src: url("{ttf}/DejaVuSans-Bold.ttf"); font-weight: bold; }}
    @font-face {{ font-family: DejaVu; src: url("{ttf}/DejaVuSans-Oblique.ttf"); font-style: italic; }}
    @font-face {{ font-family: DejaVu; src: url("{ttf}/DejaVuSans-BoldOblique.ttf"); font-weight: bold; font-style: italic; }}
    @font-face {{ font-family: dvmono; src: url("{ttf}/DejaVuSansMono.ttf"); }}
    """ + """
    @page { size: A4; margin: 2cm 1.8cm 2cm 1.8cm;
            @frame footer { -pdf-frame-content: footer; bottom: 0.8cm; margin-left: 1.8cm; margin-right: 1.8cm; height: 0.6cm; } }
    body { font-family: DejaVu; font-size: 10pt; line-height: 1.35; color: #111; }
    h1 { font-size: 22pt; margin-top: 4cm; text-align: center; }
    h2 { font-size: 15pt; color: #1c5cab; margin-top: 14pt; border-bottom: 1px solid #c3c2b7; }
    h3 { font-size: 12pt; margin-top: 10pt; }
    .titlepage h2 { text-align: center; border: none; color: #333; font-size: 13pt; }
    .titlepage p { text-align: center; font-size: 12pt; }
    table { border-collapse: collapse; width: 100%; margin: 6pt 0; -pdf-keep-in-frame-mode: shrink; }
    th { background-color: #e9eef6; font-weight: bold; }
    th, td { border: 0.5px solid #c3c2b7; padding: 2pt 3pt; font-size: 7pt; vertical-align: top; }
    code { font-family: dvmono; font-size: 8pt; }
    pre { font-family: dvmono; font-size: 8pt; background-color: #f4f4f2; padding: 6pt; }
    img { width: 16cm; }
    em { color: #444; }
    .pagebreak { page-break-after: always; }
    blockquote { font-size: 8.5pt; color: #333; margin-left: 12pt; }
    """
    html = (f"<html><head><meta charset='utf-8'><style>{css}</style></head><body>{body}"
            f"<div id='footer' style='text-align:center;font-size:8pt;color:#777'>Saksham Kala — Capstone report — page <pdf:pagenumber/></div>"
            f"</body></html>")
    with open(REP / "report.pdf", "wb") as fh:
        res = pisa.CreatePDF(html, dest=fh, encoding="utf-8")
    print("report.pdf written" if not res.err else f"PDF errors: {res.err}")


if __name__ == "__main__":
    main()
